#!/bin/bash

# 1. Проверяем, что переданы РОВНО два аргумента
if [ "$#" -ne 2 ]; then
    echo "Ошибка: Требуется два числа."
    echo "Использование: $0 <число1> <число2>"
    exit 1
fi

# Присваиваем аргументы переменным
num1=$1
num2=$2

# --- 2. Логика перестановки чисел (чтобы большее было первым) ---
if [ "$num1" -lt "$num2" ]; then
    echo "Меняем порядок: $num2 и $num1"
    # Обмен значениями
    temp=$num1
    num1=$num2
    num2=$temp
else
    echo "Порядок правильный: $num1 и $num2"
fi

# --- 3. Проверка деления на ноль (после перестановки num2 будет меньшим) ---
if [ "$num2" -eq 0 ]; then
    echo "Ошибка: Деление на ноль невозможно."
    exit 1
fi

# --- 4. Вычисления ---
# Используем $(( )) для арифметики
quotient=$(( num1 / num2 ))
remainder=$(( num1 % num2 ))

# --- 5. Вывод результатов ---
echo "Частное (результат): $quotient"
echo "Остаток: $remainder"

